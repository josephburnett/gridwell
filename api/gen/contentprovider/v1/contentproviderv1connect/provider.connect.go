// provider.proto is the CONTENT PROVIDER surface (docs/v2-design.md §2.2)
// — the v2 plugin contract. A provider is STATELESS: it answers from its
// source (a directory tree, the process table, a mail account) in its own
// stable string KEYS, and never sees ids, layout, or a database. The node
// owns all of those: it mints numeric ids against keys, stores placement
// and framing in the external's memory DB, and serves the full Gridwell
// surface to clients — a provider is invisible on the federation wire.
//
// Key stability is the provider's one hard contract: a key names the same
// logical thing forever (a path relative to the configured root, a
// message-id, "pid:1234"). Changing the key scheme orphans every stored
// reference, exactly as re-minting ids would.
//
// Unimplemented is always polite: Search = no results, ServeContent =
// 404, Watch = no events, WriteContent = read-only, GetPreview = no
// thumbnail, Delete = refused. A minimal provider is Info + List +
// ReadContent.

